/** Тексты по пути: страницы, категории, проекты. undefined — маршрута нет в копирайте. */
export function seoCopyFor(routePath: string): SeoCopy | undefined {
  if (PAGE_SEO[routePath]) return PAGE_SEO[routePath];
  const slug = routePath.match(/^\/portfolio\/([^/]+)$/u)?.[1];
  if (!slug) return undefined;
  return (CATEGORY_SEO as Record<string, SeoCopy>)[slug] ?? PROJECT_SEO[slug];
}

/** Вид работы из title проекта («… — монтаж образовательного курса | YELYGINN») для альтов постеров. */
export function projectWork(slug: string): string | undefined {
  const title = PROJECT_SEO[slug]?.title;
  if (!title) return undefined;
  const i = title.lastIndexOf(" — ");
  return i < 0 ? undefined : title.slice(i + 3).replace(/\s*\|.*$/u, "");
}
