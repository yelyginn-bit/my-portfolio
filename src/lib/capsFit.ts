/** Неизвестный символ считаем самым широким из таблицы — ошибка в безопасную сторону. */
const WIDEST = Math.max(...Object.values(ADVANCE));
/** Запас на кернинг и округление: 3%. */
const SAFETY = 1.03;

/** Куски без «естественных» мест переноса: слова по пробелам, после дефиса и тире — новый кусок. */
export function wordsOf(text: string): string[] {
  return text.split(/\s+/).flatMap((word) => word.split(/(?<=[-\u2010-\u2014])(?=.)/u)).filter(Boolean);
}

/** Ширина слова в em при трекинге `tracking` (em на букву, например -0.035). */
export function wordEm(word: string, tracking = -0.035): number {
  let sum = 0;
  for (const ch of word.toUpperCase()) sum += ADVANCE[ch] ?? WIDEST;
  return sum + tracking * [...word].length;
}

/** Самое широкое слово текста, em. Округлено вверх до тысячных, с запасом SAFETY. */
export function longestWordEm(text: string, tracking = -0.035): number {
  const widest = Math.max(0.5, ...wordsOf(text).map((word) => wordEm(word, tracking)));
  return Math.ceil(widest * SAFETY * 1000) / 1000;
}
